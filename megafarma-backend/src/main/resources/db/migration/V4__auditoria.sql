-- Megafarma · V4: bitacora de auditoria (HU-45).
-- Registra quien hizo cada operacion sensible, desde que IP y si tuvo exito:
-- inicios de sesion, intentos fallidos, accesos denegados, ventas, anulaciones,
-- cambios de catalogo, inventario y usuarios. No se modifica ni se borra desde la API.

CREATE TABLE auditoria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha   TIMESTAMP    NOT NULL,
    usuario VARCHAR(50)  NOT NULL,
    accion  VARCHAR(40)  NOT NULL,
    detalle VARCHAR(250),
    ip      VARCHAR(45),
    exito   BOOLEAN      NOT NULL
);

CREATE INDEX ix_auditoria_fecha ON auditoria (fecha);
CREATE INDEX ix_auditoria_usuario ON auditoria (usuario);
CREATE INDEX ix_auditoria_accion ON auditoria (accion);
