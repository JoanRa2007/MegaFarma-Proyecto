-- Megafarma · Esquema inicial
-- SQL estandar: funciona igual en PostgreSQL (dev/prod) y en H2 (perfil local y pruebas).

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(30)  NOT NULL,
    descripcion VARCHAR(150),
    CONSTRAINT uk_roles_nombre UNIQUE (nombre)
);

CREATE TABLE usuarios (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(50)  NOT NULL,
    password_hash     VARCHAR(100) NOT NULL,
    nombre_completo   VARCHAR(120) NOT NULL,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    rol_id            BIGINT       NOT NULL,
    creado_en         TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuarios_username UNIQUE (username),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (rol_id) REFERENCES roles (id)
);

CREATE TABLE categorias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(80)  NOT NULL,
    descripcion VARCHAR(200),
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

CREATE TABLE productos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(30)    NOT NULL,
    nombre           VARCHAR(150)   NOT NULL,
    principio_activo VARCHAR(150),
    presentacion     VARCHAR(100),
    laboratorio      VARCHAR(100),
    precio_venta     NUMERIC(10, 2) NOT NULL,
    stock_minimo     INTEGER        NOT NULL DEFAULT 0,
    requiere_receta  BOOLEAN        NOT NULL DEFAULT FALSE,
    activo           BOOLEAN        NOT NULL DEFAULT TRUE,
    categoria_id     BIGINT         NOT NULL,
    creado_en        TIMESTAMP      NOT NULL,
    actualizado_en   TIMESTAMP      NOT NULL,
    CONSTRAINT uk_productos_codigo UNIQUE (codigo),
    CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
    CONSTRAINT ck_productos_precio CHECK (precio_venta > 0),
    CONSTRAINT ck_productos_stock_minimo CHECK (stock_minimo >= 0)
);

CREATE TABLE lotes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id       BIGINT      NOT NULL,
    numero_lote       VARCHAR(40) NOT NULL,
    fecha_vencimiento DATE        NOT NULL,
    cantidad_inicial  INTEGER     NOT NULL,
    cantidad_actual   INTEGER     NOT NULL,
    precio_compra     NUMERIC(10, 2),
    dado_de_baja      BOOLEAN     NOT NULL DEFAULT FALSE,
    creado_en         TIMESTAMP   NOT NULL,
    CONSTRAINT uk_lotes_producto_numero UNIQUE (producto_id, numero_lote),
    CONSTRAINT fk_lotes_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_lotes_cantidad CHECK (cantidad_actual >= 0)
);

CREATE TABLE clientes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento   VARCHAR(10)  NOT NULL,
    numero_documento VARCHAR(15)  NOT NULL,
    nombre           VARCHAR(150) NOT NULL,
    telefono         VARCHAR(20),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_clientes_documento UNIQUE (numero_documento)
);

CREATE TABLE ventas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             VARCHAR(20),
    fecha              TIMESTAMP      NOT NULL,
    cliente_id         BIGINT,
    usuario_id         BIGINT         NOT NULL,
    estado             VARCHAR(15)    NOT NULL,
    medio_pago         VARCHAR(15)    NOT NULL,
    total              NUMERIC(12, 2) NOT NULL,
    motivo_anulacion   VARCHAR(250),
    anulada_en         TIMESTAMP,
    clave_idempotencia VARCHAR(60),
    CONSTRAINT uk_ventas_numero UNIQUE (numero),
    CONSTRAINT uk_ventas_idempotencia UNIQUE (clave_idempotencia),
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT fk_ventas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE detalle_ventas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        BIGINT         NOT NULL,
    producto_id     BIGINT         NOT NULL,
    lote_id         BIGINT         NOT NULL,
    cantidad        INTEGER        NOT NULL,
    precio_unitario NUMERIC(10, 2) NOT NULL,
    subtotal        NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_detalle_venta FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT fk_detalle_lote FOREIGN KEY (lote_id) REFERENCES lotes (id),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0)
);

-- Kardex: cada entrada, salida, ajuste o baja deja un movimiento.
CREATE TABLE movimientos_inventario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id        BIGINT      NOT NULL,
    lote_id            BIGINT      NOT NULL,
    tipo               VARCHAR(25) NOT NULL,
    cantidad           INTEGER     NOT NULL,
    stock_resultante   INTEGER     NOT NULL,
    motivo             VARCHAR(250),
    referencia         VARCHAR(40),
    clave_idempotencia VARCHAR(60),
    usuario_id         BIGINT      NOT NULL,
    fecha              TIMESTAMP   NOT NULL,
    CONSTRAINT uk_movimientos_idempotencia UNIQUE (clave_idempotencia),
    CONSTRAINT fk_movimientos_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT fk_movimientos_lote FOREIGN KEY (lote_id) REFERENCES lotes (id),
    CONSTRAINT fk_movimientos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX ix_lotes_vencimiento ON lotes (fecha_vencimiento);
CREATE INDEX ix_ventas_fecha ON ventas (fecha);
CREATE INDEX ix_movimientos_producto ON movimientos_inventario (producto_id, fecha);
CREATE INDEX ix_productos_nombre ON productos (nombre);
