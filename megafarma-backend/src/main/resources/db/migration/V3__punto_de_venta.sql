-- Megafarma · V3: punto de venta.
-- Pagos mixtos con vuelto, desglose del IGV y comprobantes electronicos
-- (boleta y factura en modo demostracion, sin envio a SUNAT).

-- Desglose de la venta: los precios incluyen IGV (18 %).
ALTER TABLE ventas ADD COLUMN subtotal NUMERIC(12, 2);
ALTER TABLE ventas ADD COLUMN igv NUMERIC(12, 2);
-- Efectivo entregado por el cliente y vuelto devuelto.
ALTER TABLE ventas ADD COLUMN monto_recibido NUMERIC(12, 2);
ALTER TABLE ventas ADD COLUMN vuelto NUMERIC(12, 2);
-- Comprobante emitido (BOLETA o FACTURA) y su numero B001-00000001.
ALTER TABLE ventas ADD COLUMN tipo_comprobante VARCHAR(10);
ALTER TABLE ventas ADD COLUMN numero_comprobante VARCHAR(13);

-- Ventas anteriores: se calcula su desglose de IGV.
UPDATE ventas SET subtotal = ROUND(total / 1.18, 2), igv = total - ROUND(total / 1.18, 2);

-- Un registro por cada forma de pago usada en la venta (pago mixto).
CREATE TABLE pagos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id   BIGINT         NOT NULL,
    medio      VARCHAR(15)    NOT NULL,
    monto      NUMERIC(12, 2) NOT NULL,
    referencia VARCHAR(40),
    CONSTRAINT fk_pagos_venta FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT ck_pagos_monto CHECK (monto > 0)
);

-- Ventas anteriores: un unico pago por el total con su medio de pago.
INSERT INTO pagos (venta_id, medio, monto)
SELECT id, medio_pago, total FROM ventas WHERE total > 0;

-- Correlativo de cada serie de comprobantes.
CREATE TABLE series_comprobante (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(10) NOT NULL,
    serie         VARCHAR(4)  NOT NULL,
    ultimo_numero INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uk_series_serie UNIQUE (serie)
);

INSERT INTO series_comprobante (tipo, serie, ultimo_numero) VALUES
    ('BOLETA', 'B001', 0),
    ('FACTURA', 'F001', 0);

-- Comprobante electronico generado para la venta (XML UBL 2.1).
CREATE TABLE comprobantes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT         NOT NULL,
    tipo             VARCHAR(10)    NOT NULL,
    serie            VARCHAR(4)     NOT NULL,
    numero           INTEGER        NOT NULL,
    cliente_tipo_doc VARCHAR(10),
    cliente_num_doc  VARCHAR(15),
    cliente_nombre   VARCHAR(150),
    op_gravada       NUMERIC(12, 2) NOT NULL,
    igv              NUMERIC(12, 2) NOT NULL,
    total            NUMERIC(12, 2) NOT NULL,
    fecha_emision    TIMESTAMP      NOT NULL,
    estado           VARCHAR(20)    NOT NULL,
    hash             VARCHAR(64)    NOT NULL,
    xml              VARCHAR(20000) NOT NULL,
    CONSTRAINT uk_comprobantes_venta UNIQUE (venta_id),
    CONSTRAINT uk_comprobantes_serie_numero UNIQUE (serie, numero),
    CONSTRAINT fk_comprobantes_venta FOREIGN KEY (venta_id) REFERENCES ventas (id)
);
